"""Convert Discord emoji images into WoW TGA textures + Lua data for TwitchEmotes_Dogesmile.

Usage:  python tools/build.py [folder ...]

Default folders: src/public, then src/private if it exists. src/private is git-ignored and never
released; an image there replaces a public one with the same "@<id>" (or adds a new emote).

Each image's file name (without extension, and without an optional "@<id>" suffix) becomes the
emote name; in chat you type :name:
Static images -> 32x32 RLE TGA. Animated GIF/WEBP -> vertical 32px frame strip + animation metadata.
"""
import math
import re
import sys
from pathlib import Path

from PIL import Image, ImageSequence

ADDON_DIR = Path(__file__).resolve().parent.parent
OUT_DIR = ADDON_DIR / "Emotes"
LUA_FILE = ADDON_DIR / "EmoteData.lua"
SIZE = 32
MAX_FRAMES = 64  # 64 * 32px = 2048px, the largest texture height we produce
PER_MENU = 40
ICON_SOURCE = "Dogesmile"  # emote used as the addon list icon
EXTS = {".png", ".gif", ".webp", ".jpg", ".jpeg"}


def fit(frame: Image.Image) -> Image.Image:
    frame = frame.convert("RGBA")
    frame.thumbnail((SIZE, SIZE), Image.LANCZOS)
    canvas = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    canvas.paste(frame, ((SIZE - frame.width) // 2, (SIZE - frame.height) // 2))
    return canvas


def convert(src: Path, name: str):
    im = Image.open(src)
    n = getattr(im, "n_frames", 1)
    if n <= 1:
        fit(im).save(OUT_DIR / f"{name}.tga", rle=True)
        return None

    frames, durations = [], []
    for f in ImageSequence.Iterator(im):
        frames.append(fit(f.copy()))
        durations.append(f.info.get("duration", 100) or 100)
    step = math.ceil(len(frames) / MAX_FRAMES)  # drop frames evenly if too long
    frames = frames[::step]
    avg_ms = sum(durations) / len(durations) * step
    fps = max(1, min(30, round(1000 / avg_ms)))
    height = 1 << math.ceil(math.log2(len(frames) * SIZE))  # power-of-two texture
    strip = Image.new("RGBA", (SIZE, height), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        strip.paste(f, (0, i * SIZE))
    strip.save(OUT_DIR / f"{name}.tga", rle=True)
    return {"nFrames": len(frames), "imageHeight": height, "framerate": fps}


def sources(dirs):
    """Images keyed by Discord id (or name); later folders override earlier ones."""
    found = {}
    for d in dirs:
        for src in d.iterdir():
            if src.suffix.lower() in EXTS:
                stem, _, eid = src.stem.partition("@")
                found[eid or stem.lower()] = src
    return sorted(found.values(), key=lambda p: p.stem.lower())


def main():
    if len(sys.argv) > 1:
        dirs = [Path(a) for a in sys.argv[1:]]
    else:
        dirs = [d for d in (ADDON_DIR / "src" / "public", ADDON_DIR / "src" / "private") if d.is_dir()]
    print("Sources:", ", ".join(str(d) for d in dirs), end="\n\n")
    OUT_DIR.mkdir(exist_ok=True)
    for old in OUT_DIR.glob("*.tga"):
        old.unlink()

    emotes, used = [], set()
    for src in sources(dirs):
        name = re.sub(r"[^A-Za-z0-9_]", "_", src.stem.split("@")[0])
        # Windows/WoW file names are case-insensitive (pepecry vs PepeCRY), so keep files unique
        file, n = name, 2
        while file.lower() in used:
            file, n = f"{name}_{n}", n + 1
        used.add(file.lower())
        anim = convert(src, file)
        emotes.append((name, file, anim))
        if name == ICON_SOURCE:
            fit(Image.open(src)).resize((64, 64), Image.LANCZOS).save(ADDON_DIR / "icon.tga", rle=True)
        print(f"{name:30s} {'animated, %d frames' % anim['nFrames'] if anim else 'static'}")

    lines = ["-- Generated by tools/build.py; do not edit by hand.", "Dogesmile_EmoteData = {"]
    for name, file, anim in emotes:
        if anim:
            lines.append(
                f'\t{{ "{name}", "{file}", {{ nFrames = {anim["nFrames"]}, frameWidth = {SIZE}, frameHeight = {SIZE}, '
                f'imageWidth = {SIZE}, imageHeight = {anim["imageHeight"]}, framerate = {anim["framerate"]} }} }},'
            )
        else:
            lines.append(f'\t{{ "{name}", "{file}" }},')
    lines += ["}", f"Dogesmile_PerMenu = {PER_MENU}", ""]
    LUA_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"\n{len(emotes)} emotes written to {OUT_DIR}")


if __name__ == "__main__":
    main()
